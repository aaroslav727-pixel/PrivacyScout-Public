struct TipsView: View {
    var body: some View {
        NavigationStack {
            List {
                Section {
                    Text("Советы про приватность: что включить в iOS и какие привычки помогают меньше «светиться». Помните: анонимность — это не кнопка, а набор компромиссов.")
                        .font(.footnote)
                        .foregroundStyle(.secondary)
                }

                ForEach(TipsData.sections) { section in
                    Section {
                        ForEach(section.tips) { tip in
                            DisclosureGroup {
                                Text(tip.body)
                                    .font(.footnote)
                                    .foregroundStyle(.secondary)
                                    .fixedSize(horizontal: false, vertical: true)
                                    .padding(.vertical, 4)
                            } label: {
                                Text(tip.title)
                                    .font(.subheadline.weight(.medium))
                            }
                        }
                    } header: {
                        Label(section.title, systemImage: section.icon)
                    }
                }
            }
            .navigationTitle("Приватность и анонимность")
            .navigationBarTitleDisplayMode(.inline)
        }
    }
}
